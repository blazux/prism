const {chromium}=require('playwright'),fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_EXECUTABLE_PATH});
 try{
  const context=await browser.newContext({viewport:{width:1440,height:1050}}),page=await context.newPage(),errors=[];
  context.on('page',p=>p.on('pageerror',e=>errors.push(e.message)));
  page.on('pageerror',e=>errors.push(e.message));
  await context.route('**/*',route=>{
   const url=new URL(route.request().url());
   if(url.hostname!=='theme.invalid')return route.abort();
   if(url.pathname.startsWith('/api/')){
    const body=url.pathname==='/api/me'?{authenticated:true,multiUser:false,isAdmin:true}:url.pathname==='/api/platform'?{disabledApps:[],voxDocked:false}:url.pathname==='/api/auth'?{authenticated:true,auth_enabled:false}:{};
    return route.fulfill({contentType:'application/json',body:JSON.stringify(body)});
   }
   const file=path.join(root,url.pathname);
   return fs.existsSync(file)&&fs.statSync(file).isFile()?route.fulfill({path:file}):route.fulfill({status:404,body:''});
  });
  await page.goto('http://theme.invalid/settings.html#appearance');await page.locator('.theme-card').first().waitFor();
  const presetCount=await page.evaluate(()=>Object.keys(PrismTheme.THEMES).length);
  assert.equal(await page.getByRole('radio').count(),presetCount);
  for(const group of ['Essentials','Focus & work','Color & atmosphere','Geek & retro'])assert(await page.getByRole('button',{name:group,exact:true}).isVisible());
  await page.getByRole('button',{name:'Focus & work',exact:true}).click();
  assert((await page.getByRole('radio').count())<presetCount);
  await page.getByRole('radio',{name:'Graphite',exact:true}).focus();
  await page.keyboard.press('ArrowRight');
  assert.notEqual(await page.evaluate(()=>PrismTheme.getThemeId()),'prism-dark');
  await page.getByRole('button',{name:'Geek & retro',exact:true}).click();
  await page.getByRole('radio',{name:'Cyberpunk',exact:true}).check();
  await page.waitForTimeout(220);
  await page.locator('.settings-page').evaluate(el=>el.scrollTop=0);
  await page.screenshot({path:'/tmp/prism-themes-geek.png',fullPage:true});
  await page.getByRole('button',{name:'All themes',exact:true}).click();
  await page.getByRole('radio',{name:'Matrix',exact:true}).check();
  assert.equal(await page.locator('#appe-theme').inputValue(),'matrix');
  await page.locator('#appe-theme').selectOption('paper');
  assert(await page.getByRole('radio',{name:'Paper',exact:true}).isChecked());
  assert.equal(await page.locator('.theme-card[data-theme=paper] .theme-mode').textContent(),'Light');
  await page.waitForTimeout(220);
  await page.locator('.settings-page').evaluate(el=>el.scrollTop=0);
  await page.screenshot({path:'/tmp/prism-themes-gallery-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.locator('.settings-page').evaluate(el=>el.scrollTop=0);
  await page.screenshot({path:'/tmp/prism-themes-gallery-mobile.png',fullPage:true});
  await page.locator('.appearance-studio > summary').click();
  await page.locator('#appe-use-theme').click();
  await page.locator('#appe-preview').click();
  assert.equal(await page.locator('.theme-gallery-active').textContent(),'Preview · unsaved palette');
  await page.locator('#appe-name').fill('My custom palette');await page.locator('#appe-save').click();
  await page.waitForFunction(()=>PrismTheme.getThemeId().startsWith('custom-'));
  assert(await page.getByRole('radio',{name:'My custom palette',exact:true}).isChecked());
  assert.equal(await page.locator('#appe-custom-list .appe-del').count(),1);
  await page.getByRole('button',{name:'Your themes',exact:true}).click();
  assert.equal(await page.getByRole('radio').count(),1);
  await page.locator('#appe-custom-list .appe-del').click();
  await page.locator('.pm-box').getByRole('button',{name:'Delete',exact:true}).click();
  await page.waitForFunction(()=>!PrismTheme.getThemeId().startsWith('custom-'));
  assert.equal(await page.getByRole('radio').count(),presetCount,'deleting last custom resets the collection filter');
  const second=await context.newPage();await second.goto('http://theme.invalid/settings.html#appearance');
  await second.locator('#appe-theme').selectOption('graphite');
  await page.waitForFunction(()=>document.getElementById('appe-theme').value==='graphite');
  assert(await page.getByRole('radio',{name:'Graphite',exact:true}).isChecked());
  await second.evaluate(()=>PrismTheme.saveCustomTheme('legacy-light','Legacy light',{'--bg':'#ffffff','--bg1':'#ffffff','--bg2':'#eeeeee','--text':'#101010','--accent':'#2759b0'}));
  await page.getByRole('radio',{name:'Legacy light',exact:true}).waitFor();
  assert.equal(await page.locator('.theme-card[data-theme=legacy-light] .theme-mode').textContent(),'Light');
  assert.equal(await page.locator('#appe-custom-list .appe-del').count(),1);
  await page.locator('#appe-theme').selectOption('paper');
  if(!await page.locator('.appearance-studio').evaluate(el=>el.open))await page.locator('.appearance-studio > summary').click();
  await page.locator('#appe-accent-hex').fill('#cc36a9');
  await page.locator('#appe-accent-hex').dispatchEvent('change');
  assert.equal(await page.evaluate(()=>document.documentElement.dataset.theme),'custom-preview');
  await page.locator('.nav-item[data-tab=profile]').click();
  await page.waitForFunction(()=>document.documentElement.dataset.theme==='paper');
  assert.equal(await page.evaluate(()=>PrismTheme.getThemeId()),'paper');
  assert.equal(await page.evaluate(()=>document.documentElement.style.getPropertyValue('--bg')),await page.evaluate(()=>PrismTheme.THEMES.paper.vars['--bg']));
  assert.deepEqual(errors,[]);
  console.log('Theme gallery: grouped cards, keyboard and pointer selection, dropdown sync, preview state, custom save/delete, cross-tab changes, legacy light custom, desktop/mobile and preview restoration on leaving Appearance passed.');
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
